/** Tipo do dicionário de strings, derivado da entrada `pt` (a mais completa). */
export type Strings = (typeof STRINGS)['pt'];

/** Acessa as strings de um idioma com type-safe. */
export function t(language: Language): Strings {
  return STRINGS[language] as Strings;
}

/** Substitui placeholders `{chave}` por valores. */
export function format(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? `{${key}}`));
}
